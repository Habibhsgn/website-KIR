        function validateNIK(input) {
            const feedback = document.getElementById('nikFeedback');
            const nik = input.value.replace(/[^0-9]/g, '');
            input.value = nik;

            if (nik.length === 0) {
                feedback.textContent = '';
                feedback.className = 'form-text';
            } else if (nik.length < 16) {
                feedback.textContent = `NIK kurang ${16 - nik.length} digit`;
                feedback.className = 'form-text text-danger';
            } else if (nik.length === 16) {
                feedback.textContent = 'NIK sudah lengkap (16 digit)';
                feedback.className = 'form-text text-success';
            } else {
                feedback.textContent = 'NIK tidak boleh lebih dari 16 digit';
                feedback.className = 'form-text text-danger';
            }
        }
